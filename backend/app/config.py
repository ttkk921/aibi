"""Settings: environment variables, then backend/.env, then <data dir>/secrets.env.

backend/.env (never committed) holds what the operator sets: database, model key, domain.
secrets.env is written by `python -m app.cli setup` with what it generates (session secret,
the read-only database account) so a container's code directory can stay read-only.
Earlier sources win; nothing overrides a variable that is already set.
"""
import os
from pathlib import Path

from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(BASE_DIR / ".env")
DATA_DIR = Path(os.getenv("BI_DATA_DIR", BASE_DIR / "data"))
SECRETS_FILE = DATA_DIR / "secrets.env"
load_dotenv(SECRETS_FILE)


def _req(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"缺少环境变量 {name}，请检查 backend/.env")
    return value


DB_HOST = os.getenv("DB_HOST", "127.0.0.1")
DB_PORT = int(os.getenv("DB_PORT", "3306"))
DB_USER = _req("DB_USER")
DB_PASSWORD = _req("DB_PASSWORD")
DB_NAME = os.getenv("DB_NAME", "bi_data")

# Account to create the database and the read-only account with (setup only); default: DB_USER.
DB_ADMIN_USER = os.getenv("DB_ADMIN_USER", "") or DB_USER
DB_ADMIN_PASSWORD = os.getenv("DB_ADMIN_PASSWORD", "") or DB_PASSWORD

# The first admin account. Only used when the accounts table is still empty: a password hash from
# the single-user setup is migrated; without one, setup generates a password (data/initial_admin_password).
ADMIN_USER = os.getenv("ADMIN_USER", "admin")
ADMIN_PASSWORD_HASH = os.getenv("ADMIN_PASSWORD_HASH", "")
# Signs session cookies; generated by setup. The app refuses to start without it.
SECRET_KEY = os.getenv("SECRET_KEY", "")
# Set to 1 only when served over HTTPS.
COOKIE_SECURE = os.getenv("COOKIE_SECURE", "0") == "1"

# Read-only query API for AI agents (/api/agent). Off unless a token hash is set
# (`python -m app.cli agent-token`). Its SQL runs as a SELECT-only account without account_no.
AGENT_TOKEN_HASH = os.getenv("AGENT_TOKEN_HASH", "")
AGENT_DB_USER = os.getenv("AGENT_DB_USER", "")
AGENT_DB_PASSWORD = os.getenv("AGENT_DB_PASSWORD", "")
# Host pattern of the read-only account created by setup ('%' = anywhere the database accepts).
AGENT_DB_HOST = os.getenv("AGENT_DB_HOST", "%")
# By default only callers on the server itself are served; requests through nginx are refused.
AGENT_ALLOW_REMOTE = os.getenv("AGENT_ALLOW_REMOTE", "0") == "1"

# AI 问数 (/api/chat): an OpenAI-compatible chat completions endpoint (Command Code by default).
LLM_API_KEY = os.getenv("LLM_API_KEY") or os.getenv("COMMANDCODE_API_KEY", "")
LLM_BASE_URL = os.getenv("LLM_BASE_URL", "https://api.commandcode.ai/provider/v1").rstrip("/")
LLM_MODEL = os.getenv("LLM_MODEL", "deepseek/deepseek-v4.1-flash")
# Initial model list of the AI 设置 page (comma separated; the first default is LLM_MODEL).
# These LLM_* values only seed the page: once an admin saves a provider there, app.db wins.
LLM_MODELS = [m.strip() for m in os.getenv(
    "LLM_MODELS", "deepseek/deepseek-v4.1-flash,deepseek/deepseek-v4.1-flash-fast,deepseek/deepseek-v4-pro"
).split(",") if m.strip()]
if LLM_MODEL not in LLM_MODELS:
    LLM_MODELS.insert(0, LLM_MODEL)
LLM_MAX_TOKENS = int(os.getenv("LLM_MAX_TOKENS", "8000"))

UPLOAD_DIR = DATA_DIR / "uploads"
WEB_DIST = Path(os.getenv("BI_WEB_DIST", BASE_DIR.parent / "web" / "dist"))
# The business package of this deployment (tables, reports, knowledge); see packages/README.md.
PACKAGE_DIR = Path(os.getenv("BI_PACKAGE_DIR", BASE_DIR.parent / "packages" / "retail"))

DATA_DIR.mkdir(exist_ok=True)
UPLOAD_DIR.mkdir(exist_ok=True)
